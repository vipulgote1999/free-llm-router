/**
 * Live ModelPulseX performance source.
 *
 * The router must never depend on ModelPulseX being up: one cached fetch per
 * isolate (5 min), a 1.2 s abort, and a checked-in snapshot fallback. This
 * module never throws to callers.
 */

import { MPX_PERF, MPX_SNAPSHOT_AT } from './mpx-catalog.generated';
import { parseLeaderboard, type MpxSnapshot } from './mpx';

const TTL_MS = 5 * 60_000;
const MAX_STALE_MS = 6 * 60 * 60_000;
const DEFAULT_BASE = 'https://modelpulsex.pages.dev';

interface SourceEnv {
  MODELPULSE_URL?: unknown;
}

let cache: { snapshot: MpxSnapshot; at: number } | null = null;
let inflight: Promise<MpxSnapshot | undefined> | null = null;

/** Last-known-good snapshot generated by scripts/sync-modelpulse.mjs. */
export function bakedSnapshot(): MpxSnapshot {
  const fetchedAt = Date.parse(MPX_SNAPSHOT_AT);
  return {
    rows: MPX_PERF,
    fetchedAt: Number.isFinite(fetchedAt) ? fetchedAt : 0,
    source: 'snapshot',
    lastBenchmark: null,
    stale: !Number.isFinite(fetchedAt) || Date.now() - fetchedAt > MAX_STALE_MS,
  };
}

export function clearMpxCache(): void {
  cache = null;
  inflight = null;
}

async function fetchLive(env: SourceEnv): Promise<MpxSnapshot | undefined> {
  const base = (typeof env.MODELPULSE_URL === 'string' && env.MODELPULSE_URL.trim() !== '' ? env.MODELPULSE_URL : DEFAULT_BASE).replace(/\/+$/, '');
  try {
    const res = await fetch(`${base}/api/leaderboard?range=24h&sort=overall&profile=balanced`, {
      headers: { accept: 'application/json' },
      signal: AbortSignal.timeout(1200),
    });
    if (!res.ok) return undefined;
    const snapshot = parseLeaderboard(await res.json(), Date.now());
    if (snapshot.rows.length === 0) return undefined;

    const last = snapshot.lastBenchmark ? Date.parse(snapshot.lastBenchmark) : Number.NaN;
    // ModelPulseX's own is_stale flag fires at 18 minutes; ranking may use
    // measurements until the spec's 6-hour limit.
    const stale = Number.isFinite(last) ? Date.now() - last > MAX_STALE_MS : snapshot.stale;
    return { ...snapshot, stale };
  } catch {
    return undefined;
  }
}

/**
 * Live snapshot, or the baked snapshot when the fetch fails/returns nothing.
 * Concurrent callers share one request.
 */
export async function loadMpxSnapshot(env: SourceEnv = {}): Promise<MpxSnapshot> {
  const now = Date.now();
  if (cache && now - cache.at < TTL_MS) return cache.snapshot;
  if (inflight) return (await inflight) ?? bakedSnapshot();

  inflight = fetchLive(env);
  try {
    const live = await inflight;
    const snapshot = live ?? bakedSnapshot();
    cache = { snapshot, at: now };
    return snapshot;
  } finally {
    inflight = null;
  }
}
